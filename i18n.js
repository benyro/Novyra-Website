(function () {
  var STORAGE_KEY = "novyraLang";
  var LANGS = ["en", "sv", "no", "fi", "is", "da", "ar", "fa"];
  /**
   * [code, flagcdn ISO 3166-1 alpha-2 (lowercase), label]
   * Windows Chrome often renders flag regional-indicator emoji as letter
   * pairs ("GB", "SE") even in custom DOM with an emoji font stack, so we
   * use small raster flags instead (see setFlagImage). If a strict CSP blocks
   * third-party images, set FLAG_IMG_BASE to "/images/flags/" and vendor
   * matching 16×12 PNGs (gb.png, se.png, …).
   */
  var FLAG_IMG_BASE = "https://flagcdn.com/16x12/";

  var LANG_OPTIONS = [
    ["en", "gb", "English"],
    ["sv", "se", "Svenska"],
    ["no", "no", "Norsk"],
    ["fi", "fi", "Suomi"],
    ["is", "is", "Íslenska"],
    ["da", "dk", "Dansk"],
    ["ar", "ae", "العربية"],
    ["fa", "ir", "فارسی"]
  ];

  function setFlagImage(container, iso2) {
    if (!container || !iso2) return;
    var url = FLAG_IMG_BASE + String(iso2).toLowerCase() + ".png";
    var img = container.querySelector("img.lang-switcher__flag-img");
    if (!img) {
      container.textContent = "";
      img = document.createElement("img");
      img.className = "lang-switcher__flag-img";
      img.setAttribute("alt", "");
      img.setAttribute("loading", "lazy");
      img.width = 16;
      img.height = 12;
      container.appendChild(img);
    }
    if (img.getAttribute("src") !== url) img.setAttribute("src", url);
  }

  function findOption(code) {
    for (var i = 0; i < LANG_OPTIONS.length; i++) {
      if (LANG_OPTIONS[i][0] === code) return LANG_OPTIONS[i];
    }
    return LANG_OPTIONS[0];
  }

  var dropdownUid = 0;
  var dropdownsRegistry = [];
  var outsideHandlerBound = false;

  function bindOutsideHandlers() {
    if (outsideHandlerBound) return;
    outsideHandlerBound = true;
    /* Outside-close on bubble click so mailto links still get the same gesture. */
    document.addEventListener("click", function (e) {
      for (var i = 0; i < dropdownsRegistry.length; i++) {
        var root = dropdownsRegistry[i];
        if (!root.classList.contains("is-open")) continue;
        if (!root.contains(e.target)) closeDropdown(root);
      }
    });
    document.addEventListener("keydown", function (e) {
      if (e.key !== "Escape") return;
      for (var i = 0; i < dropdownsRegistry.length; i++) {
        var root = dropdownsRegistry[i];
        if (!root.classList.contains("is-open")) continue;
        closeDropdown(root);
        var btn = root.querySelector(".lang-switcher__btn");
        if (btn) btn.focus();
      }
    });
  }

  function openDropdown(root) {
    if (root.classList.contains("is-open")) return;
    for (var i = 0; i < dropdownsRegistry.length; i++) {
      if (dropdownsRegistry[i] !== root) closeDropdown(dropdownsRegistry[i]);
    }
    root.classList.add("is-open");
    var btn = root.querySelector(".lang-switcher__btn");
    var list = root.querySelector(".lang-switcher__menu");
    if (btn) btn.setAttribute("aria-expanded", "true");
    if (list) list.hidden = false;
    var selected = list && list.querySelector('[aria-selected="true"]');
    var target = selected || (list && list.querySelector(".lang-switcher__option"));
    if (target) target.focus();
  }

  function closeDropdown(root) {
    if (!root.classList.contains("is-open")) return;
    root.classList.remove("is-open");
    var btn = root.querySelector(".lang-switcher__btn");
    var list = root.querySelector(".lang-switcher__menu");
    if (btn) btn.setAttribute("aria-expanded", "false");
    if (list) list.hidden = true;
  }

  function toggleDropdown(root) {
    if (root.classList.contains("is-open")) closeDropdown(root);
    else openDropdown(root);
  }

  function pickOption(root, li) {
    var code = li.getAttribute("data-value");
    closeDropdown(root);
    var btn = root.querySelector(".lang-switcher__btn");
    if (btn) btn.focus();
    if (code) setLang(code);
  }

  function moveActive(list, delta, absolute) {
    var opts = list.querySelectorAll(".lang-switcher__option");
    if (!opts.length) return;
    var idx = -1;
    for (var i = 0; i < opts.length; i++) {
      if (opts[i] === document.activeElement) {
        idx = i;
        break;
      }
    }
    var next;
    if (absolute === "first") next = 0;
    else if (absolute === "last") next = opts.length - 1;
    else {
      if (idx === -1) idx = 0;
      next = (idx + delta + opts.length) % opts.length;
    }
    opts[next].focus();
  }

  function syncDropdown(root, lang, t) {
    var btn = root.querySelector(".lang-switcher__btn");
    var btnFlag = root.querySelector(".lang-switcher__btn .lang-switcher__flag");
    var btnLabel = root.querySelector(".lang-switcher__btn .lang-switcher__label");
    var row = findOption(lang);
    if (btn) btn.setAttribute("aria-label", t("a11y.chooseLanguage"));
    if (btnFlag) setFlagImage(btnFlag, row[1]);
    if (btnLabel) btnLabel.textContent = row[2];
    var opts = root.querySelectorAll(".lang-switcher__option");
    for (var i = 0; i < opts.length; i++) {
      var match = opts[i].getAttribute("data-value") === lang;
      opts[i].setAttribute("aria-selected", match ? "true" : "false");
      opts[i].classList.toggle("is-active", match);
    }
  }

  function buildDropdown(wrap, lang, t) {
    var root = document.createElement("div");
    root.className = "lang-switcher__dropdown";
    root.setAttribute("data-novyra-lang-dropdown", "1");

    var listId = "novyraLangList-" + ++dropdownUid;

    var btn = document.createElement("button");
    btn.type = "button";
    btn.className = "lang-switcher__btn";
    btn.setAttribute("aria-haspopup", "listbox");
    btn.setAttribute("aria-expanded", "false");
    btn.setAttribute("aria-controls", listId);

    var btnFlag = document.createElement("span");
    btnFlag.className = "lang-switcher__flag";
    btnFlag.setAttribute("aria-hidden", "true");

    var btnLabel = document.createElement("span");
    btnLabel.className = "lang-switcher__label";

    var chev = document.createElement("span");
    chev.className = "lang-switcher__chev";
    chev.setAttribute("aria-hidden", "true");
    chev.innerHTML =
      '<svg viewBox="0 0 10 6" width="10" height="6" focusable="false" aria-hidden="true">' +
      '<path d="M1 1l4 4 4-4" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/>' +
      "</svg>";

    btn.appendChild(btnFlag);
    btn.appendChild(btnLabel);
    btn.appendChild(chev);

    var list = document.createElement("ul");
    list.className = "lang-switcher__menu";
    list.id = listId;
    list.setAttribute("role", "listbox");
    list.hidden = true;

    LANG_OPTIONS.forEach(function (row) {
      var li = document.createElement("li");
      li.className = "lang-switcher__option";
      li.setAttribute("role", "option");
      li.setAttribute("data-value", row[0]);
      li.setAttribute("aria-selected", "false");
      li.setAttribute("tabindex", "-1");

      var f = document.createElement("span");
      f.className = "lang-switcher__flag";
      f.setAttribute("aria-hidden", "true");
      setFlagImage(f, row[1]);

      var n = document.createElement("span");
      n.className = "lang-switcher__name";
      n.textContent = row[2];

      li.appendChild(f);
      li.appendChild(n);
      li.addEventListener("click", function () {
        pickOption(root, li);
      });
      list.appendChild(li);
    });

    btn.addEventListener("click", function (e) {
      e.preventDefault();
      toggleDropdown(root);
    });

    btn.addEventListener("keydown", function (e) {
      if (e.key === "ArrowDown" || e.key === "ArrowUp" || e.key === "Enter" || e.key === " ") {
        e.preventDefault();
        openDropdown(root);
      }
    });

    list.addEventListener("keydown", function (e) {
      var key = e.key;
      if (key === "ArrowDown") {
        e.preventDefault();
        moveActive(list, 1);
      } else if (key === "ArrowUp") {
        e.preventDefault();
        moveActive(list, -1);
      } else if (key === "Home") {
        e.preventDefault();
        moveActive(list, 0, "first");
      } else if (key === "End") {
        e.preventDefault();
        moveActive(list, 0, "last");
      } else if (key === "Enter" || key === " ") {
        e.preventDefault();
        var active = document.activeElement;
        if (active && active.classList.contains("lang-switcher__option")) {
          pickOption(root, active);
        }
      } else if (key === "Tab") {
        closeDropdown(root);
      } else if (key && key.length === 1 && /[a-zA-Z]/.test(key)) {
        var letter = key.toLowerCase();
        var opts = list.querySelectorAll(".lang-switcher__option");
        for (var i = 0; i < opts.length; i++) {
          var name = opts[i].querySelector(".lang-switcher__name");
          if (name && name.textContent && name.textContent.toLowerCase().charAt(0) === letter) {
            opts[i].focus();
            break;
          }
        }
      }
    });

    root.appendChild(btn);
    root.appendChild(list);
    wrap.appendChild(root);
    dropdownsRegistry.push(root);
    bindOutsideHandlers();
    syncDropdown(root, lang, t);
  }

  function mountLangSwitcher(wrap, lang, t) {
    var legacy = wrap.querySelector("select.lang-switcher__select");
    if (legacy && legacy.parentNode) legacy.parentNode.removeChild(legacy);
    var root = wrap.querySelector(".lang-switcher__dropdown");
    if (root) {
      syncDropdown(root, lang, t);
      return;
    }
    buildDropdown(wrap, lang, t);
  }

  function getDict(code) {
    return (window.NOVYRA_I18N_MESSAGES && window.NOVYRA_I18N_MESSAGES[code]) || window.NOVYRA_I18N_MESSAGES.en;
  }

  function pickLangFromNavigator() {
    var raw = (typeof navigator !== "undefined" && (navigator.language || navigator.userLanguage)) || "en";
    var n = String(raw).toLowerCase().slice(0, 2);
    if (n === "nb" || n === "nn") n = "no";
    if (n === "prs") n = "fa";
    if (LANGS.indexOf(n) === -1) n = "en";
    return n;
  }

  function getLang() {
    try {
      var s = localStorage.getItem(STORAGE_KEY);
      if (s && LANGS.indexOf(s) !== -1) return s;
    } catch (e) {}
    return pickLangFromNavigator();
  }

  function setLang(code) {
    if (LANGS.indexOf(code) === -1) code = "en";
    try {
      localStorage.setItem(STORAGE_KEY, code);
    } catch (e) {}
    applyI18n(code);
    try {
      window.dispatchEvent(new CustomEvent("novyra:i18n-applied", { detail: { lang: code } }));
    } catch (e2) {}
  }

  function tPath(dict, path) {
    var parts = path.split(".");
    var cur = dict;
    for (var i = 0; i < parts.length; i++) {
      if (cur == null) return "";
      cur = cur[parts[i]];
    }
    return typeof cur === "string" ? cur : "";
  }

  function expandPlaceholders(str, dict) {
    if (!str) return "";
    return str
      .split("{{iconTiktok}}")
      .join(escapeHtml(tPath(dict, "brand.tiktok")))
      .split("{{iconTiktokLive}}")
      .join(escapeHtml(tPath(dict, "brand.tiktokLive")));
  }

  function escapeHtml(s) {
    return String(s)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }

  function applyI18n(code) {
    var lang = code || getLang();
    var dict = getDict(lang);
    var enBase = window.NOVYRA_I18N_MESSAGES && window.NOVYRA_I18N_MESSAGES.en;
    var flats = window.NOVYRA_I18N_FLAT_OVERRIDES && window.NOVYRA_I18N_FLAT_OVERRIDES[lang];
    function t(key) {
      if (flats && Object.prototype.hasOwnProperty.call(flats, key) && flats[key]) {
        return flats[key];
      }
      var v = tPath(dict, key);
      if (v) return v;
      return enBase ? tPath(enBase, key) : "";
    }
    document.documentElement.setAttribute("lang", lang === "no" ? "nb" : lang);
    document.documentElement.setAttribute("dir", lang === "ar" || lang === "fa" ? "rtl" : "ltr");

    var titleKey = document.body && document.body.getAttribute("data-i18n-title");
    if (titleKey) {
      var tit = t(titleKey);
      if (tit) document.title = tit;
    }

    document.querySelectorAll("[data-i18n-desc]").forEach(function (meta) {
      var k = meta.getAttribute("data-i18n-desc");
      if (!k) return;
      var c = t(k);
      if (c) meta.setAttribute("content", c);
    });

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (!key) return;
      var href = el.getAttribute && el.getAttribute("href");
      var hrefLc = href && String(href).toLowerCase();
      if (el.tagName === "A" && hrefLc && hrefLc.indexOf("mailto:") === 0) return;
      var val = t(key);
      if (typeof val === "string" && val.length) el.textContent = val;
    });

    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-html");
      if (!key) return;
      var val = t(key);
      if (typeof val !== "string" || !val.length) return;
      el.innerHTML = expandPlaceholders(val, dict);
      /* Stale cached i18n.js sometimes still supplies old "partner ecosystem" English; normalize in the DOM. */
      if (key === "home.featLivePartnerBody" && lang === "en" && /partner\s+ecosystem/i.test(el.innerHTML)) {
        el.innerHTML = el.innerHTML.replace(/partner\s+ecosystem/gi, "official partner programme");
      }
    });

    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      var raw = el.getAttribute("data-i18n-attr");
      if (!raw) return;
      raw.split(";").forEach(function (pair) {
        var bits = pair.split("|");
        if (bits.length < 2) return;
        var attr = bits[0].trim();
        var k = bits[1].trim();
        var val = t(k);
        if (typeof val === "string" && val.length) el.setAttribute(attr, val);
      });
    });

    document.querySelectorAll("[data-lang-switcher]").forEach(function (wrap) {
      mountLangSwitcher(wrap, lang, t);
    });

    var contactMailto = "mailto:contact@novyraagency.com";
    document.querySelectorAll("a.footer-email").forEach(function (a) {
      a.setAttribute("href", contactMailto);
    });
    document.querySelectorAll("[data-i18n='team.partnerCtaEmail']").forEach(function (el) {
      var wrap = el.closest && el.closest("a");
      if (wrap) wrap.setAttribute("href", contactMailto);
    });

    window.__novyraI18nApplied = true;
    window.__novyraLang = lang;
  }

  window.NovyraI18n = {
    getLang: getLang,
    setLang: setLang,
    apply: applyI18n,
    LANGS: LANGS
  };

  /* First full apply runs from locale-bootstrap.js after NOVYRA_I18N_MESSAGES is
   * populated for sv/no/fi/is/da/ar/fa; applying here would use English for dict
   * while localStorage lang is non-en (getDict falls back to en). */
})();
